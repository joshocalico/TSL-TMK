// Exhaustive control flow through `finally` (SPEC 8.1, D49): every way out (normal, return, break, continue, throw, and a
// labelled break and continue) from every position (try, catch, finally), with a second try nested in each position of
// the first, also with every way out from every position. Each function logs the path it took, and V8 is the reference.
//
// `tmk exc-gen` writes corpus/lower/exc/gen_finally_<a>_<b>.ts: one file for each place the inner try sits and each
// position of the outer exit, so a failure names its family. The output is deterministic and checked in.
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const POSITIONS = ["try", "catch", "finally"] as const;
export const EXITS = [
  "normal",
  "return",
  "break",
  "continue",
  "throw",
  "breakOuter",
  "continueOuter",
] as const;
type Pos = (typeof POSITIONS)[number];
type Exit = (typeof EXITS)[number];

function exitCode(e: Exit, tag: string): string {
  switch (e) {
    case "normal":
      return "";
    case "return":
      return `if (go) return log + "R${tag}";`;
    case "break":
      return `if (go) break;`;
    case "continue":
      return `if (go) continue;`;
    case "throw":
      return `if (go) throw new Error("${tag}");`;
    case "breakOuter":
      return `if (go) break outer;`;
    case "continueOuter":
      return `if (go) continue outer;`;
  }
}

/**
 * One try statement. `exitAt` puts an exit in one position; `nest` puts another try in one position. Reaching the catch
 * needs the try to throw first, so a catch-position exit or nest makes the try throw.
 */
function tryText(
  ind: string,
  tag: string,
  exitAt: { pos: Pos; exit: Exit } | null,
  nest: { pos: Pos; text: string } | null,
  binding: boolean,
): string {
  const at = (p: Pos): string => {
    const parts: string[] = [];
    if (nest !== null && nest.pos === p) parts.push(nest.text);
    if (exitAt !== null && exitAt.pos === p)
      parts.push(`${ind}  ${exitCode(exitAt.exit, `${tag}${p[0]}`)}`);
    return parts.join("\n");
  };
  const needThrow = exitAt?.pos === "catch" || nest?.pos === "catch";
  const c = binding
    ? `catch (e) {\n${ind}  log += "C${tag}" + tagOf(e);`
    : `catch {\n${ind}  log += "C${tag}";`;
  return [
    `${ind}try {`,
    `${ind}  log += "T${tag}";`,
    needThrow ? `${ind}  if (go) throw new Error("t${tag}");` : "",
    at("try"),
    `${ind}  log += "t${tag}";`,
    `${ind}} ${c}`,
    at("catch"),
    `${ind}  log += "c${tag}";`,
    `${ind}} finally {`,
    `${ind}  log += "F${tag}";`,
    at("finally"),
    `${ind}  log += "f${tag}";`,
    `${ind}}`,
  ]
    .filter((l) => l !== "")
    .join("\n");
}

export function genFile(place: Pos, outerPos: Pos, only: Exit): { ts: string; cases: unknown[] } {
  const fns: string[] = [];
  const cases: unknown[] = [];
  let n = 0;
  for (const outerExit of [only]) {
    for (const innerPos of POSITIONS) {
      for (const innerExit of EXITS) {
        const name = `f_${place}_${outerPos}_${outerExit}_${innerPos}_${innerExit}`;
        const binding = n % 2 === 0;
        n++;
        const inner = tryText("        ", "i", { pos: innerPos, exit: innerExit }, null, !binding);
        const body = tryText(
          "      ",
          "o",
          { pos: outerPos, exit: outerExit },
          { pos: place, text: inner },
          binding,
        );
        fns.push(
          [
            `export function ${name}(go: boolean): string {`,
            `  let log = "";`,
            `  ${outerExit.endsWith("Outer") || innerExit.endsWith("Outer") ? "outer: " : ""}for (let i = 0; i < 2; i++) {`,
            `    log += "[" + i;`,
            `    for (let j = 0; j < 2; j++) {`,
            `      log += "<" + j;`,
            body,
            `      log += ">";`,
            `    }`,
            `    log += "]";`,
            `  }`,
            `  return log;`,
            `}`,
          ].join("\n"),
        );
        cases.push({ fn: name, args: [true] }, { fn: name, args: [false] });
      }
    }
  }
  const head = [
    "// Generated by tools/exc-gen.ts (tmk exc-gen): every way out of every position of a try, nested in every position of",
    `// another, here with the inner try in the outer one's ${place} and the outer exit (${only}) in its ${outerPos}. V8 is the reference.`,
    "function tagOf(e: unknown): string {",
    '  return e instanceof Error ? "(" + e.message + ")" : "(?)";',
    "}",
    "",
  ].join("\n");
  return { ts: `${head}${fns.join("\n\n")}\n`, cases };
}

export function writeAll(root: string): string[] {
  const dir = join(root, "corpus/lower/exc");
  mkdirSync(dir, { recursive: true });
  const out: string[] = [];
  for (const place of POSITIONS) {
    for (const outerPos of POSITIONS) {
      // One file per outer exit, 21 functions each: a file of all seven is 360,000 instructions, and with the verifier
      // after every pass (as every milestone runs) a batch of a few took longer than a batch's wall-clock limit.
      for (const outerExit of EXITS) {
        const { ts, cases } = genFile(place, outerPos, outerExit);
        const base = join(dir, `gen_finally_${place}_${outerPos}_${outerExit}`);
        writeFileSync(`${base}.ts`, ts);
        writeFileSync(`${base}.cases.json`, `${JSON.stringify(cases, null, 1)}\n`);
        out.push(`${base}.ts`, `${base}.cases.json`);
      }
    }
  }
  // As the repo's formatter has them, so a regenerated file is byte for byte the checked-in one.
  execFileSync(join(root, "node_modules/.bin/oxfmt"), out, { cwd: root, stdio: "ignore" });
  return out;
}

if (process.argv[1]?.endsWith("exc-gen.ts") === true) {
  const root = new URL("..", import.meta.url).pathname;
  for (const f of writeAll(root)) console.log(f);
}
