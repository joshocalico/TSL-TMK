// Writes compiler/rt/case-tables.ts from what V8 here does: toUpperCase and toLowerCase on every code point, and the two
// properties the final-sigma rule asks about. Native's tables are V8's by construction, and `tmk milestone native-f` checks
// every code point against whichever V8 runs it, so a new Unicode version shows as a failure, not a difference.
// `node tools/gen-case-tables.ts`
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT } from "./corpus.ts";

interface Run {
  lo: number;
  hi: number;
  stride: number;
  delta: number;
}

function table(f: (s: string) => string): { runs: Run[]; special: number[][] } {
  const runs: Run[] = [];
  const special: number[][] = [];
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    const s = String.fromCodePoint(cp);
    const out = f(s);
    if (out === s) continue;
    const chars = [...out];
    if (chars.length !== 1) {
      const units: number[] = [];
      for (let i = 0; i < out.length; i++) units.push(out.charCodeAt(i));
      special.push([cp, ...units]);
      continue;
    }
    const delta = chars[0]!.codePointAt(0)! - cp;
    const last = runs[runs.length - 1];
    if (last !== undefined && last.delta === delta) {
      const step = cp - last.hi;
      if (last.stride === 0 || last.stride === step) {
        if (step <= 2) {
          last.stride = step;
          last.hi = cp;
          continue;
        }
      }
    }
    runs.push({ lo: cp, hi: cp, stride: 0, delta });
  }
  return { runs, special };
}

function ranges(re: RegExp): number[] {
  const out: number[] = [];
  let start = -1;
  for (let cp = 0; cp <= 0x110000; cp++) {
    const on =
      cp <= 0x10ffff && !(cp >= 0xd800 && cp <= 0xdfff) && re.test(String.fromCodePoint(cp));
    if (on && start < 0) start = cp;
    if (!on && start >= 0) {
      out.push(start, cp - 1);
      start = -1;
    }
  }
  return out;
}

const up = table((s) => s.toUpperCase());
const low = table((s) => s.toLowerCase());
// The sigma's own rule is context: alone it lowers to the plain sigma, and that's the table's entry.
const cased = ranges(/\p{Cased}/u);
const ignorable = ranges(/\p{Case_Ignorable}/u);

const flat = (t: { runs: Run[] }): number[] =>
  t.runs.flatMap((r) => [r.lo, r.hi, r.stride === 0 ? 1 : r.stride, r.delta]);
const specials = (t: { special: number[][] }): { index: number[]; data: number[] } => {
  const index: number[] = [];
  const data: number[] = [];
  for (const [cp, ...units] of t.special) {
    index.push(cp!, data.length, units.length);
    data.push(...units);
  }
  return { index, data };
};
const arr = (name: string, xs: number[]): string =>
  `export const ${name} = new Int32Array([${xs.join(",")}]);\n`;
const su = specials(up);
const sl = specials(low);
writeFileSync(
  join(ROOT, "compiler/rt/case-tables.ts"),
  `// Generated by tools/gen-case-tables.ts, from V8 ${process.versions.v8}, Unicode ${process.versions.unicode}. Don't edit.\n` +
    arr("UP_RUNS", flat(up)) +
    arr("UP_SPECIAL", su.index) +
    arr("UP_DATA", su.data) +
    arr("LOW_RUNS", flat(low)) +
    arr("LOW_SPECIAL", sl.index) +
    arr("LOW_DATA", sl.data) +
    arr("CASED", cased) +
    arr("IGNORABLE", ignorable),
);
const n =
  flat(up).length +
  su.index.length +
  su.data.length +
  flat(low).length +
  sl.index.length +
  sl.data.length +
  cased.length +
  ignorable.length;
console.log(`${n} words, ${n * 4} bytes`);
